let currentLanguage = "ko";
let languageChanging = false;


/* ==========================================
   실제 번역 적용
========================================== */

function applyLanguage(lang) {

  const dictionary = translations[lang];

  if (!dictionary) return;


  document
    .querySelectorAll("[data-i18n]")
    .forEach(element => {

      const key =
        element.dataset.i18n;

      if (
        Object.prototype
          .hasOwnProperty
          .call(dictionary, key)
      ) {
        element.textContent =
          dictionary[key];
      }

    });


  document
    .querySelectorAll(".lang button")
    .forEach(button => {

      button.classList.toggle(
        "active",
        button.dataset.lang === lang
      );

    });


  document.documentElement.lang = lang;

  currentLanguage = lang;
}


/* ==========================================
   안전한 애니메이션 실행
========================================== */

async function playAnimation(
  element,
  keyframes,
  options
) {

  if (
    !element ||
    typeof element.animate !== "function"
  ) {
    return;
  }


  let animation;

  try {

    animation =
      element.animate(
        keyframes,
        options
      );

    await animation.finished;

  } catch (error) {

    /* 애니메이션 실패가
       번역 기능을 막지 않도록 함 */

  } finally {

    if (animation) {

      try {
        animation.cancel();
      } catch (error) {
        /* 무시 */
      }

    }

  }

}


/* ==========================================
   언어 변경
========================================== */

async function changeLanguage(lang) {

  if (
    languageChanging ||
    lang === currentLanguage ||
    !translations[lang]
  ) {
    return;
  }


  languageChanging = true;

  const wrap =
    document.querySelector(".wrap");


  try {

    /* 현재 화면이 위로 살짝 사라짐 */

    await playAnimation(
      wrap,
      [
        {
          opacity:1,
          transform:
            "translateY(0px)"
        },
        {
          opacity:0,
          transform:
            "translateY(-8px)"
        }
      ],
      {
        duration:220,
        easing:"ease-in",
        fill:"forwards"
      }
    );


    /*
      중요:
      애니메이션 성공 여부와 관계없이
      반드시 번역 실행
    */

    applyLanguage(lang);


    /* 번역된 화면 등장 */

    await playAnimation(
      wrap,
      [
        {
          opacity:0,
          transform:
            "translateY(10px)"
        },
        {
          opacity:1,
          transform:
            "translateY(0px)"
        }
      ],
      {
        duration:380,
        easing:
          "cubic-bezier(.22,1,.36,1)",
        fill:"both"
      }
    );


  } finally {

    /*
      어떤 오류가 발생해도
      화면이 숨겨진 채 남지 않도록 복구
    */

    if (wrap) {

      wrap.style.opacity = "";
      wrap.style.transform = "";

    }

    languageChanging = false;

  }

}


/* ==========================================
   첫 화면 진입 애니메이션
========================================== */

async function entranceAnimation() {

  const wrap =
    document.querySelector(".wrap");

  if (!wrap) return;


  await playAnimation(
    wrap,
    [
      {
        opacity:0,
        transform:
          "translateY(18px)"
      },
      {
        opacity:1,
        transform:
          "translateY(0px)"
      }
    ],
    {
      duration:750,
      easing:
        "cubic-bezier(.22,1,.36,1)",
      fill:"both"
    }
  );

}


/* ==========================================
   시작
========================================== */

document.addEventListener(
  "DOMContentLoaded",
  () => {

    /* 최초 한국어 적용 */

    applyLanguage("ko");


    /* 언어 버튼 연결 */

    document
      .querySelectorAll(".lang button")
      .forEach(button => {

        button.addEventListener(
          "click",
          () => {

            const lang =
              button.dataset.lang;

            changeLanguage(lang);

          }
        );

      });


    /* 첫 진입 애니메이션 */

    requestAnimationFrame(
      () => {
        entranceAnimation();
      }
    );

  }
);
